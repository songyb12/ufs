async def seed_n5_vocab_extended() -> dict:
    """Insert extended N5 vocabulary into jp_vocabulary table.

    Skips individual words already present (checked by word field) so
    this function is safe to call multiple times.
    """
    db = await get_db()

    inserted = 0
    skipped = 0

    for word, reading, meaning, level, pos, ex_ja, ex_ko in N5_VOCAB_EXTENDED:
        # Duplicate check by word
        cursor = await db.execute(
            "SELECT id FROM jp_vocabulary WHERE word = ?", (word,)
        )
        row = await cursor.fetchone()
        if row:
            skipped += 1
            continue

        await db.execute(
            """INSERT INTO jp_vocabulary
               (word, reading, meaning, jlpt_level, part_of_speech, example_ja, example_ko)
               VALUES (?, ?, ?, ?, ?, ?, ?)""",
            (word, reading, meaning, level, pos, ex_ja, ex_ko),
        )
        inserted += 1

    # Create SRS cards for newly inserted vocab
    if inserted > 0:
        await db.execute(
            """INSERT INTO jp_srs_cards (vocab_id, next_review)
               SELECT id, date('now') FROM jp_vocabulary
               WHERE id NOT IN (SELECT vocab_id FROM jp_srs_cards)"""
        )
        await db.commit()

    logger.info(
        "N5 extended vocab seed complete: %d inserted, %d skipped (duplicates)",
        inserted,
        skipped,
    )
    return {
        "status": "ok",
        "inserted": inserted,
        "skipped": skipped,
        "total_attempted": len(N5_VOCAB_EXTENDED),
    }
