async def seed_reading_data() -> int:
    """Insert N5 reading passages and questions. Returns passage count."""
    db = await get_db()

    # Check if data already exists
    cursor = await db.execute("SELECT COUNT(*) FROM jp_reading_passage")
    count = (await cursor.fetchone())[0]
    if count > 0:
        logger.info("Reading passages already seeded (%d rows), skipping", count)
        return count

    passage_count = 0
    for p in PASSAGES:
        await db.execute(
            """INSERT INTO jp_reading_passage (title, content_jp, content_ko, jlpt_level, category, word_count)
               VALUES (?, ?, ?, ?, ?, ?)""",
            (p["title"], p["content_jp"], p["content_ko"], "N5", p["category"], p["word_count"]),
        )
        # Get the inserted passage ID
        id_cursor = await db.execute("SELECT last_insert_rowid()")
        passage_id = (await id_cursor.fetchone())[0]

        for q in p["questions"]:
            await db.execute(
                """INSERT INTO jp_reading_question
                   (passage_id, question_jp, question_ko, option_a, option_b, option_c, option_d, correct_answer, explanation)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (passage_id, q[0], q[1], q[2], q[3], q[4], q[5], q[6], q[7]),
            )

        passage_count += 1

    await db.commit()
    logger.info("Seeded %d reading passages", passage_count)
    return passage_count
